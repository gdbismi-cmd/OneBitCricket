#!/usr/bin/env python3
"""Bake Silkscreen (regular + bold) at its native 8 px grid into source/font.h.

Run from switch/:  python3 tools/mkfont.py
Needs Pillow. The output is committed, so builds don't need Python.
"""
from PIL import Image, ImageDraw, ImageFont

ASC, ROWS = 9, 11  # baseline row and glyph cell height at 8 px


def bake(path):
    f = ImageFont.truetype(path, 8)
    glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        im = Image.new('1', (24, ROWS), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((0, ASC), ch, font=f, fill=1, anchor='ls')
        rows = []
        for y in range(ROWS):
            bits = 0
            for x in range(16):
                if im.getpixel((x, y)):
                    bits |= 1 << x
            rows.append(bits)
        glyphs.append((adv, rows))
    return glyphs


def emit(name, glyphs):
    out = [f'static const Glyph {name}[95] = {{']
    for i, (adv, rows) in enumerate(glyphs):
        out.append('  {%d, {%s}}, // %r' % (adv, ','.join('0x%x' % r for r in rows), chr(32 + i)))
    out.append('};')
    return '\n'.join(out)


if __name__ == '__main__':
    hdr = ['// Generated by tools/mkfont.py from Silkscreen (SIL Open Font License, see fonts/OFL.txt).',
           '#pragma once', '#include <cstdint>',
           f'enum {{ FONT_ASC = {ASC}, FONT_ROWS = {ROWS} }};',
           'struct Glyph { uint8_t adv; uint16_t rows[FONT_ROWS]; };',
           emit('FONT_REG', bake('fonts/Silkscreen-Regular.ttf')),
           emit('FONT_BOLD', bake('fonts/Silkscreen-Bold.ttf'))]
    open('source/font.h', 'w').write('\n'.join(hdr) + '\n')
